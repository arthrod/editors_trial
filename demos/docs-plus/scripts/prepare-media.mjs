/**
 * Copies the demo document into `public/` and extracts its embedded media.
 *
 * The docs.plus importer hands every embedded image to an injected
 * `uploadImage` boundary that re-hosts it on the pad's media route. A static
 * site has no upload route, so the media is shipped next to the document and
 * `uploadImage` returns a same-folder URL — the same shape the trial harness
 * used (a loopback HTTP server holding the real bytes).
 */
import { mkdir, readFile, writeFile, rm } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { unzipSync } from 'fflate'

import { hashBytes } from '../shared/media-hash.mjs'

const here = path.dirname(fileURLToPath(import.meta.url))
const appDir = path.resolve(here, '..')
const publicDir = path.join(appDir, 'public')
const mediaDir = path.join(publicDir, 'media')
const generatedDir = path.join(appDir, 'src', 'generated')

const source = process.argv[2] ?? '/tmp/demos/docs-plus.docx'

const bytes = new Uint8Array(await readFile(source))
await rm(mediaDir, { recursive: true, force: true })
await mkdir(mediaDir, { recursive: true })

await writeFile(path.join(publicDir, 'document.docx'), bytes)

const zip = unzipSync(bytes)
const manifest = {}

for (const [name, entry] of Object.entries(zip)) {
  if (!name.startsWith('word/media/')) continue
  if (!/\.(png|jpe?g|gif|webp|svg|bmp|ico|tiff|avif|heic|heif|jxl)$/i.test(name)) continue
  const data = entry instanceof Uint8Array ? entry : new Uint8Array(entry)
  const key = hashBytes(data)
  const fileName = `${key}-${path.basename(name)}`
  await writeFile(path.join(mediaDir, fileName), data)
  manifest[key] = `media/${fileName}`
}

await mkdir(generatedDir, { recursive: true })
await writeFile(
  path.join(generatedDir, 'media-manifest.ts'),
  `// Generated by scripts/prepare-media.mjs — do not edit by hand.\n` +
    `export const MEDIA_MANIFEST: Record<string, string> = ${JSON.stringify(manifest, null, 2)}\n`
)

console.log(`[prepare-media] document: ${bytes.length} bytes`)
console.log(`[prepare-media] media files: ${Object.keys(manifest).length}`)
for (const [key, file] of Object.entries(manifest)) console.log(`  ${key} -> ${file}`)
