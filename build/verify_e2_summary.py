#!/usr/bin/env python3
"""Check Report E2's results tables against the cell facts, with code of its own (#227).

    python3 build/verify_e2_summary.py [report.md] [facts.json]

The results at the top of Report E2 are generated by build/perf_e2_summary.py,
which also writes its figures into out/facts.json. The number gate reads that
file, so a figure the generator got wrong would match itself there. This
script shares nothing with the generator: it reads the rendered report's
tables, recomputes every cell from the two rounds' cell facts
(`perf.e2.<editor>.<criterion>[.<measure>].<workload>.primary|reproduction`),
and fails on any cell or range sentence that differs.
"""
from __future__ import annotations

import json
import math
import re
import sys
from pathlib import Path
from statistics import median

BASE = Path(__file__).resolve().parent.parent
REPORT = BASE / 'reports' / 'Report E2 - Speed in the Browser (2026).md'
FACTS = BASE / 'out' / 'facts.json'

# heading in the report -> (criterion, measure)
TABLES = {
    'Opening a document': ('C11', ''),
    'Typing one character': ('C05', 'warm_steady'),
    'Clicking to place the caret': ('C07', ''),
    'Pasting a block of text': ('C08', ''),
    'Undoing': ('C09', ''),
    'Scrolling': ('C10', ''),
    'Memory with the document open': ('C17', 'quiescent'),
}
FOUR = ('500 words', '5,000 words', '50,000 words', '250,000 words')
# The document sizes each table must show, whatever the report's own header says.
REQUIRED = {heading: FOUR + ('500,000 words',) if heading == 'Opening a document' else FOUR for heading in TABLES}
COLUMNS = {'500 words': 'prose-500w', '5,000 words': 'prose-5kw', '50,000 words': 'prose-50kw',
           '250,000 words': 'prose-250kw', '500,000 words': 'prose-500kw'}
ROUND = re.compile(r'(first|second): not enough samples \(n = (\d+) of (\d+); reasons ([^)]*)\)')


def _middle(cell: dict) -> float:
    stats = cell.get('stats') or {}
    value = stats.get('median')
    return float(value if isinstance(value, (int, float)) else median(cell['kept_ms']))


NOTHING_TO_MEASURE = {'no_deferred_work'}


def _recorded(cells) -> set:
    return {reason for cell in cells if isinstance(cell, dict)
            for listed in (cell.get('refusal_reasons') or {}).values() for reason in listed}


def _counted(reason: str) -> dict:
    """{round: (kept, scheduled, {code: count} or None)} of the rounds a reason names."""
    seen = {}
    for name, kept, scheduled, body in ROUND.findall(reason):
        primary = body.split('; also ')[0]
        pairs = re.findall(r'([A-Za-z_]+): (\d+)', primary)
        whole = '; '.join('%s: %s' % pair for pair in pairs) == primary.strip()
        seen[name] = (int(kept), int(scheduled), dict((k, int(v)) for k, v in pairs) if whole else None)
    return seen


def _refused(reason: str, cells=()) -> str:
    if 'medians outside tolerance' in reason:
        return 'varied'
    seen = _counted(reason)
    if sorted(seen) != ['first', 'second']:
        return 'no figure'
    kinds = set()
    for kept, scheduled, counts in seen.values():
        if kept != 0 or counts is None or sum(counts.values()) != scheduled:
            return 'no figure'
        kinds |= set(counts)
    if kinds == {'not_applicable'}:
        recorded = _recorded(cells)
        # "does not apply" is true only when every refused launch recorded that there was nothing to measure.
        return 'does not apply' if recorded and not recorded - NOTHING_TO_MEASURE else 'not measured'
    if kinds and not kinds - {'crash', 'editor_crash'}:
        return 'crashed'
    return 'no figure'


def _shown(value: float, unit: str) -> str:
    if unit == 'bytes':
        mib = value / 1048576
        return ('%.1f GiB' % (mib / 1024)) if mib >= 1024 else ('%d MiB' % round(mib))
    if value >= 100000:
        return '%d s' % round(value / 1000)
    if value >= 1000:
        return '%.1f s' % (value / 1000)
    return '%d ms' % round(value)


def _below(frame: float) -> str:
    return 'under %d ms' % math.ceil(frame)


def _round_figures(rounds: dict):
    """The printed figure of each round of a cell whose rounds disagreed, or None when a median is missing."""
    values = [(rounds.get(name) or {}).get('median') for name in ('first', 'second')]
    if not all(isinstance(value, (int, float)) for value in values):
        return None
    unit = rounds.get('sample_unit') or 'ms'
    # Each round against the redraw interval it recorded itself; the cell's is the fallback for older facts.
    frames = [(rounds.get(name) or {}).get('frame_interval_ms') or rounds.get('frame_interval_ms') or 0
              for name in ('first', 'second')]
    texts = [_below(frame) if unit != 'bytes' and frame and value < frame else _shown(value, unit)
             for value, frame in zip(values, frames)]
    if texts[0] == texts[1]:
        if unit == 'bytes':
            texts = ['%.1f MiB' % (value / 1048576) for value in values]
        else:
            texts = [('%.2f s' % (value / 1000)) if value >= 1000 else ('%.1f ms' % value) for value in values]
    return list(zip(values, texts))


def expected_cell(facts: dict, editor: str, criterion: str, measure: str, workload: str):
    """(text, value or None, counts in the range sentence)."""
    base = 'perf.e2.%s.%s%s.%s' % (editor, criterion, '.' + measure if measure else '', workload)
    state = facts.get(base + '.reproduced')
    if state is None:
        return '—', None, False
    if not state:
        figures = _round_figures(facts.get(base + '.rounds') or {})
        if figures:
            low, high = sorted(figures)
            return '%s to %s' % (low[1], high[1]), None, False
        return _refused(str(facts.get(base + '.reason') or ''), (facts.get(base + '.primary'), facts.get(base + '.reproduction'))), None, False
    one, two = facts[base + '.primary'], facts[base + '.reproduction']
    value = (_middle(one) + _middle(two)) / 2
    unit = one.get('sample_unit') or 'ms'
    below = unit != 'bytes' and all(_middle(c) < (c.get('frame_interval_ms') or 0) for c in (one, two))
    text = _below(max(one.get('frame_interval_ms') or 0, two.get('frame_interval_ms') or 0)) if below else _shown(value, unit)
    if criterion == 'C11' and not (one.get('content_verified') is True and two.get('content_verified') is True):
        return text + ' (text not checked)', value, False
    return text, value, True


def expected_why_parts(facts: dict, editor: str, criterion: str, measure: str, workload: str) -> list:
    """Text the appendix row of a cell must contain: each round's figure and launches, or its kept launches."""
    base = 'perf.e2.%s.%s%s.%s' % (editor, criterion, '.' + measure if measure else '', workload)
    rounds = facts.get(base + '.rounds') or {}
    figures = _round_figures(rounds)
    if figures:
        # Each figure in the clause of its own round: swapping the two rounds must not pass.
        clauses = ('The first round gave %s (%d launches)', 'and the second %s (%d launches)')
        return [clause % (text, (rounds[name].get('n') or 0))
                for clause, (_value, text), name in zip(clauses, figures, ('first', 'second'))]
    parts = []
    for name, (kept, scheduled, _counts) in _counted(str(facts.get(base + '.reason') or '')).items():
        parts.append('%s round: %d of %d launches kept' % (name.capitalize(), kept, scheduled))
        # ... and the recorded reason in words (CodeRabbit, #240): a term the explanation of that reason cannot
        # do without. A reason this check has no term for asks for nothing more.
        cell = facts.get(base + ('.primary' if name == 'first' else '.reproduction')) or {}
        for reasons in (cell.get('refusal_reasons') or {}).values():
            for reason in reasons:
                for piece in reason.split('; '):
                    term = _reason_term(piece)
                    if term and term not in parts:
                        parts.append(term)
    return parts


def _reason_term(reason: str):
    """A word the explanation of a recorded refusal reason must use; None when this check knows none."""
    if reason == 'no_glyph_geometry_to_witness_the_keystrokes_own_paint':
        return 'outline'
    if 'crashed' in reason or reason.startswith('page_lost'):
        return 'crashed'
    return {'no_painted_frame': 'no redraw', 'correctness: fixture_body_mismatch': 'did not match',
            'cpu_throttled': 'throttled', 'expected_edit_not_confirmed': 'not found',
            'document_content_unverifiable': 'could not read'}.get(reason)


def expected_sentence(columns, editors: int) -> str:
    """columns: [(title, [(value, text), ...])] of one table, in order; editors: the table's rows."""
    usable = [(title, cells) for title, cells in columns if len(cells) >= 2]
    if not usable:
        return ''
    picked = [usable[0]] if len(usable) == 1 else [usable[0], usable[-1]]
    out = []
    for index, (title, cells) in enumerate(picked):
        texts = [text for _value, text in cells]
        if len(set(texts)) == 1:
            spread = 'all ' + texts[0]
        else:
            timed = sorted((value, text) for value, text in cells if not text.startswith('under '))
            # "under N ms" cells, by N: the tightest bound is the low end; with no timed cell the loosest is the high end.
            bounds = sorted({text for _value, text in cells if text.startswith('under ')}, key=lambda text: float(text.split()[1]))
            low = bounds[0] if bounds else timed[0][1]
            high = timed[-1][1] if timed else bounds[-1]
            spread = 'from %s to %s' % (low, high)
        head = 'At %s, %d of %d editors have a figure' if index == 0 else 'at %s, %d of %d'
        out.append(head % (title, len(cells), editors) + ', ' + spread)
    return '; '.join(out) + '.'


def check(report_text: str, facts: dict, display: dict) -> list:
    """Every difference between the report's results tables and the facts, as text."""
    slug = {name: key for key, name in display.items()}
    start = report_text.index('\n## The results')
    section = report_text[start:report_text.index('\n## ', start + 5)]
    problems, found = [], set()
    if 'under 1 frame' in section:
        problems.append("the results print 'under 1 frame': a reader has no frame, print the time (\"under 17 ms\")")
    unsettled = {}  # (heading, editor name, column title) -> (printed text, editor, criterion, measure, workload)
    for block in re.split(r'\n### ', section)[1:]:
        heading = block.split('\n', 1)[0].strip()
        if heading not in TABLES:
            problems.append('unknown table %r' % heading)
            continue
        found.add(heading)
        criterion, measure = TABLES[heading]
        rows = [line for line in block.split('\n') if line.startswith('|')]
        titles = [cell.strip() for cell in rows[0].strip('|').split('|')][1:]
        if tuple(titles) != REQUIRED[heading]:
            problems.append('%s: columns are %r, expected %r' % (heading, titles, list(REQUIRED[heading])))
            titles = [title for title in titles if title in COLUMNS]
        columns = [(title, []) for title in titles]
        for row in rows[2:]:
            cells = [cell.strip() for cell in row.strip('|').split('|')]
            editor = slug.get(cells[0])
            if editor is None:
                problems.append('%s: unknown editor %r' % (heading, cells[0]))
                continue
            for index, title in enumerate(titles):
                text, value, counts = expected_cell(facts, editor, criterion, measure, COLUMNS[title])
                if cells[1 + index] != text:
                    problems.append('%s / %s / %s: report says %r, the facts give %r'
                                    % (heading, cells[0], title, cells[1 + index], text))
                if counts:
                    columns[index][1].append((value, text))
                elif text != '—' and not text.endswith('(text not checked)'):
                    unsettled[(heading, cells[0], title)] = (text, editor, criterion, measure, COLUMNS[title])
        printed = [line for line in block.split('\n') if line.startswith('At ')]
        sentence = expected_sentence(columns, len(rows) - 2)
        if (printed[0] if printed else '') != sentence:
            problems.append('%s: range sentence is %r, the facts give %r' % (heading, printed[0] if printed else '', sentence))
        # An editor with a cell in the facts must have a row.
        listed = {slug.get(row.strip('|').split('|')[0].strip()) for row in rows[2:]}
        for editor in display:
            has = any(facts.get('perf.e2.%s.%s%s.%s.reproduced' % (editor, criterion, '.' + measure if measure else '', w)) is not None
                      for w in COLUMNS.values())
            if has and editor not in listed:
                problems.append('%s: %s has cells in the facts and no row' % (heading, display[editor]))
    # A table the facts can fill must be there: the generator leaves one out only when no cell has a figure.
    for heading, (criterion, measure) in TABLES.items():
        if heading in found:
            continue
        if any(expected_cell(facts, editor, criterion, measure, COLUMNS[title])[2]
               for editor in display for title in REQUIRED[heading]):
            problems.append('%r: the facts hold figures and the report has no table' % heading)
    if not found:
        problems.append('no results table found')
    problems += _check_appendix(report_text, facts, unsettled)
    return problems


def _check_appendix(report_text: str, facts: dict, unsettled: dict) -> list:
    """Appendix J against the cells the facts leave without a single figure: one row each, and the why's numbers."""
    marker = '\n## Appendix J'
    if marker not in report_text:
        return ['Appendix J is missing and %d results cell(s) have no single figure' % len(unsettled)] if unsettled else []
    start = report_text.index(marker)
    following = report_text.find('\n## ', start + 5)
    body = report_text[start:following if following != -1 else len(report_text)]
    problems, listed = [], {}
    for line in body.split('\n'):
        if not line.startswith('|') or line.startswith('| Table') or line.startswith('|---'):
            continue
        cells = [cell.strip() for cell in line.strip().strip('|').split('|')]
        if len(cells) < 5:
            problems.append('Appendix J: a row has %d columns, expected 5: %r' % (len(cells), line[:80]))
            continue
        where = (cells[0], cells[1], cells[2])
        if where in listed:
            problems.append('Appendix J: %s / %s / %s has two rows' % where)
            continue
        listed[where] = (cells[3], ' | '.join(cells[4:]))
    for where, (text, editor, criterion, measure, workload) in unsettled.items():
        if where not in listed:
            problems.append('Appendix J: %s / %s / %s prints %r in the results and has no row' % (*where, text))
            continue
        printed, why = listed[where]
        if printed != text:
            problems.append('Appendix J: %s / %s / %s says %r, the facts give %r' % (*where, printed, text))
        for part in expected_why_parts(facts, editor, criterion, measure, workload):
            if part not in why:
                problems.append('Appendix J: the why of %s / %s / %s does not say %r' % (*where, part))
    for where in listed:
        if where not in unsettled:
            problems.append('Appendix J: %s / %s / %s has a row, and that cell has a single figure or is not in the results' % where)
    return problems


def main(argv) -> int:
    sys.path.insert(0, str(BASE))
    from build.perf_e2_tables import DISPLAY
    report = Path(argv[1]) if len(argv) > 1 else REPORT
    facts = json.loads((Path(argv[2]) if len(argv) > 2 else FACTS).read_text(encoding='utf-8'))
    problems = check(report.read_text(encoding='utf-8'), facts, DISPLAY)
    for problem in problems:
        print('E2-SUMMARY-MISMATCH ' + problem)
    print('E2 summary: %s' % ('every cell and sentence matches the cell facts' if not problems
                              else '%d mismatch(es)' % len(problems)))
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
