#!/usr/bin/env python3
"""
Find why the report .docx is refused by Word 16.115.

The report is generated by pandoc, so it is not the corpus: it is a
pandoc/reference.docx package. This script probes the leading hypothesis
(the TOC field's w:dirty="true") and, failing that, bisects the report's
body the same way the corpus was bisected.

usage: python3 build/report_bisect.py
"""
import os
import re
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from wxml import split_body  # noqa: E402
from word_probe import probe  # noqa: E402

BASE = "/Users/arthrod/temp/T/editors_trial"
REPORT = os.path.join(BASE, "Open-Source DOCX Editors Re-verified Against "
                               "Code and Measured Round-Trip (2026).docx")

with zipfile.ZipFile(REPORT) as _z:
    DOC = _z.read("word/document.xml").decode("utf-8")
HEAD, BLOCKS, TAIL = split_body(DOC)
BODY = DOC[DOC.index("<w:body>") + len("<w:body>"):DOC.index("</w:body>")]

print("report body blocks: %d" % len(BLOCKS))

# 1 - the leading hypothesis
clean = BODY.replace(' w:dirty="true"', "")
probe("rep_no_dirty", clean, src=REPORT)

# 2 - control: the untouched report body
probe("rep_as_is", BODY, src=REPORT)

# 3 - bisect the body
SECTPR = BLOCKS[-1] if BLOCKS[-1].startswith("<w:sectPr") else ""
CONTENT = BLOCKS[:-1] if SECTPR else BLOCKS


def body_of(keep):
    return "".join(CONTENT[i] for i in keep) + SECTPR


n = len(CONTENT)
mid = n // 2
probe("rep_first_half", body_of(list(range(mid))), src=REPORT)
probe("rep_second_half", body_of(list(range(mid, n))), src=REPORT)
